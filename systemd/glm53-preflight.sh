#!/usr/bin/env bash
# glm53-preflight.sh — gatekeeper for GLM-5.3-Flash TP=2 (2x DGX Spark) starts.
# Run by glm53-flash.service (ExecStartPre) and safe to run standalone.
# On success, writes env.runtime (env.tp2-low + the freshly probed RoCEv2 GID)
# and exits 0. Never hard-codes environment-dependent values (GID lesson:
# a stale pin passes preflight but fails NCCL at QP RTR — probe every launch).
set -uo pipefail

KNAP=/home/sakkout/glm53-knapcio
ENV_BASE="$KNAP/env.tp2-low"
ENV_RUNTIME="$KNAP/env.runtime"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/glm53-watchdog"
WORKER="spark-8485"
fail=0; warn=0
ok()  { echo "[preflight] OK  $*"; }
bad() { echo "[preflight] FAIL $*"; fail=$((fail+1)); }
note(){ echo "[preflight] WARN $*"; warn=$((warn+1)); }
mkdir -p "$STATE_DIR"
cd "$KNAP"   # env.tp2-low sources profiles/current.env relative to this dir

# --- 1. Env file + key vars ---
if [ ! -f "$ENV_BASE" ]; then bad "env file missing: $ENV_BASE"; exit 1; fi
# shellcheck disable=SC1090
source "$ENV_BASE"
for v in HOSTS IPS IMAGE CTN PORT MODEL_DIR DRAFT_DIR OVERLAY_REMOTE FABRIC_IFACE IB_HCA; do
  val="${!v:-}"
  [ -n "$val" ] || bad "env var $v empty/missing in env.tp2-low"
done
PORT="${PORT:-8000}"; CTN="${CTN:-glm53a}"; IMAGE="${IMAGE:-}"

# --- 2. Both nodes reachable ---
read -r -a H <<<"$HOSTS"
if ! ssh -o ConnectTimeout=8 -o BatchMode=yes "$WORKER" true 2>/dev/null; then
  bad "worker $WORKER unreachable over ssh"
fi
ok "worker ssh reachable"

# --- 3. swappiness=0 on BOTH nodes (resets to 60 on reboot; a nonzero value
#        wedges the worker mid-shard-load). Hard gate — honest failure beats a
#        silent wedge. Fix: sudo sysctl vm.swappiness=0 on each node. ---
sw_h=$(cat /proc/sys/vm/swappiness 2>/dev/null || echo x)
sw_w=$(ssh -o ConnectTimeout=8 -o BatchMode=yes "$WORKER" 'cat /proc/sys/vm/swappiness' 2>/dev/null || echo x)
if [ "$sw_h" = "0" ] && [ "$sw_w" = "0" ]; then
  ok "swappiness=0 both nodes"
else
  bad "swappiness must be 0 on both nodes (head=$sw_h worker=$sw_w) — run: sudo sysctl vm.swappiness=0 on each"
fi

# --- 4. RoCEv2 GID probe on the pinned HCA (IB_HCA) on BOTH nodes ---
# Lowest global (non-fe80) RoCE v2 GID index. Indexes may shift after
# kernel/driver events — probe every launch, never pin across launches.
probe_gid() {  # $1 = device, runs locally or over ssh via PROBE_REMOTE
  local dev="$1" i ty g
  for i in 0 1 2 3 4 5 6 7; do
    ty=$(cat /sys/class/infiniband/$dev/ports/1/gid_attrs/types/$i 2>/dev/null)
    g=$(cat /sys/class/infiniband/$dev/ports/1/gids/$i 2>/dev/null)
    case "$g" in fe80*|"") continue ;; esac
    [ "$ty" = "RoCE v2" ] && { echo "$i"; return 0; }
  done
  return 1
}
gid_h=$(probe_gid "$IB_HCA") || bad "no RoCEv2 GID on head device $IB_HCA"
gid_w=$(ssh -o ConnectTimeout=8 -o BatchMode=yes "$WORKER" "cat /sys/class/infiniband/$IB_HCA/ports/1/gid_attrs/types/* 2>/dev/null >/dev/null; for i in 0 1 2 3 4 5 6 7; do ty=\$(cat /sys/class/infiniband/$IB_HCA/ports/1/gid_attrs/types/\$i 2>/dev/null); g=\$(cat /sys/class/infiniband/$IB_HCA/ports/1/gids/\$i 2>/dev/null); case \"\$g\" in fe80*|'') continue;; esac; [ \"\$ty\" = 'RoCE v2' ] && echo \$i && exit 0; done; exit 1") || bad "no RoCEv2 GID on worker device $IB_HCA"
if [ -n "${gid_h:-}" ] && [ "${gid_h:-}" = "${gid_w:-}" ]; then
  ok "RoCEv2 GID index $gid_h on $IB_HCA, both nodes agree"
  # Write the runtime env: base profile + the freshly probed GID.
  cat > "$ENV_RUNTIME" <<EOF
# AUTO-GENERATED by glm53-preflight.sh $(date -Is) — do not edit by hand.
# Base profile + launch-time probed RoCEv2 GID (single transport value; the
# switched TP2 launcher passes one NCCL_IB_GID_INDEX for both ranks).
source $ENV_BASE
NCCL_IB_GID_INDEX=$gid_h
EOF
else
  [ -n "${gid_h:-}" ] && [ -n "${gid_w:-}" ] && bad "GID index divergence head=$gid_h worker=$gid_w — per-rank passthrough needed, manual launch required"
fi

# --- 5. Ports free on head (old pair must be fully down) ---
for p in "$PORT" "${MASTER_PORT:-29669}"; do
  if ss -tln 2>/dev/null | grep -q ":$p "; then
    bad "port $p in use (head) — stop the old pair first"
  else
    ok "port $p free (head)"
  fi
done

# --- 6. Memory guards: llama-server off; DS4 emergency deployment must not
#        co-serve with GLM on GB10 unified memory ---
if systemctl --user is-active llama-server >/dev/null 2>&1; then
  bad "llama-server active alongside GLM — stop it (systemctl --user stop llama-server)"
else
  ok "llama-server inactive"
fi
if curl -fsS -m 3 http://127.0.0.1:8888/health >/dev/null 2>&1; then
  bad "DS4 emergency deployment active on :8888 — GLM+DS4 cannot co-serve; stop DS4 first"
else
  ok "DS4 not serving (:8888 closed)"
fi

# --- 7. Image + weights present on both nodes ---
docker image inspect "$IMAGE" >/dev/null 2>&1 && ok "image $IMAGE (head)" || bad "image $IMAGE missing (head)"
ssh -o ConnectTimeout=8 -o BatchMode=yes "$WORKER" "docker image inspect '$IMAGE' >/dev/null 2>&1" && ok "image $IMAGE (worker)" || bad "image $IMAGE missing (worker)"
for d in "$MODEL_DIR" "$DRAFT_DIR"; do
  [ -d "$d" ] && ok "weights dir $d (head)" || bad "weights dir missing (head): $d"
  ssh -o ConnectTimeout=8 -o BatchMode=yes "$WORKER" "test -d '$d'" && ok "weights dir $d (worker)" || bad "weights dir missing (worker): $d"
done

# --- 8. Old containers (informational; the start wrapper removes them) ---
for r in 0 1; do
  if [ $r -eq 0 ]; then
    docker ps -a --format '{{.Names}}' 2>/dev/null | grep -q "^${CTN}-r0$" && note "stale container ${CTN}-r0 present (head) — start wrapper will remove it"
  else
    ssh -o ConnectTimeout=8 -o BatchMode=yes "$WORKER" "docker ps -a --format '{{.Names}}' 2>/dev/null | grep -q '^${CTN}-r1$'" && note "stale container ${CTN}-r1 present (worker) — start wrapper will remove it"
  fi
done

echo "[preflight] done: fail=$fail warn=$warn"
[ "$fail" -eq 0 ] || { echo "[preflight] REFUSING START — fix failures above"; exit 1; }
exit 0